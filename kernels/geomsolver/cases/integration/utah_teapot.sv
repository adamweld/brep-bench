// Refused: Solvent has no surface given by a control net (a Bézier or B-spline patch from its
// 4 × 4 control points) and no solid bounded by faces sewn together: its solids are sets —
// prisms, revolutions, lofts and sweeps of plane sections, offsets and Booleans of them — and its
// one free-form surface, a point of a component traced over two formals, bounds no solid. Each
// patch's curves of constant u happen to be plane cubics, so a patch could only be imitated as a
// face family whose section's control points are the patch's Bernstein sums written out by hand as
// laws in the family's parameter — the surface computed in the document rather than given to the
// kernel as the patch it is.
